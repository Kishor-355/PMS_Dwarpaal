"""Report writer — report.md for humans, results.json for machines.

A report that only says PASS is useless. Every line here answers: which event, which
check, what was expected, what was actually found.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path


def write(out_dir: Path, run: dict) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    md = out_dir / f"report_{stamp}.md"
    js = out_dir / f"results_{stamp}.json"

    md.write_text(_markdown(run), encoding="utf-8")
    js.write_text(json.dumps(run, indent=2, default=str), encoding="utf-8")
    return md, js


def _markdown(run: dict) -> str:
    summary = run["summary"]
    lines: list[str] = []
    add = lines.append

    add("# Practice harness report\n")
    add(f"- Run ID: `{run['run_id']}`")
    add(f"- Started: {run['started']}")
    add(f"- Target: `{run['target']}`")
    add(f"- Break mode: `{run.get('break_mode') or 'none'}`")
    add("")

    verdict = "PASS" if summary["failed"] == 0 else "FAIL"
    add(f"## Verdict: **{verdict}**\n")
    add(f"{summary['passed']} passed, {summary['failed']} failed, {summary['total']} checks\n")

    add("## Scenarios\n")
    add("| Scenario | Event | Status | Checks | Failed |")
    add("| --- | --- | --- | --- | --- |")
    for scenario in run["scenarios"]:
        add(
            f"| {scenario['name']} | {scenario['event_type']} | "
            f"{'PASS' if scenario['passed'] else '**FAIL**'} | "
            f"{len(scenario['checks'])} | {len([c for c in scenario['checks'] if not c['passed']])} |"
        )
    add("")

    failures = [
        (scenario["name"], check)
        for scenario in run["scenarios"]
        for check in scenario["checks"]
        if not check["passed"]
    ]
    if failures:
        add("## Failures\n")
        for scenario_name, check in failures:
            add(f"### `{check['id']}` — {check['description']}")
            add(f"- Scenario: {scenario_name}")
            add(f"- Expected: `{check['expected']}`")
            add(f"- Actual:   `{check['actual']}`")
            if check["detail"]:
                add(f"- Detail: {check['detail']}")
            add("")

    add("## All checks\n")
    add("| ID | Scenario | Check | Expected | Actual | Result |")
    add("| --- | --- | --- | --- | --- | --- |")
    for scenario in run["scenarios"]:
        for check in scenario["checks"]:
            mark = "PASS" if check["passed"] else "**FAIL**"
            add(
                f"| {check['id']} | {scenario['name']} | {check['description']} | "
                f"`{check['expected']}` | `{check['actual']}` | {mark} |"
            )
    add("")
    add("---")
    add("Generated by the practice rig. Not a production artefact.")
    return "\n".join(lines)
